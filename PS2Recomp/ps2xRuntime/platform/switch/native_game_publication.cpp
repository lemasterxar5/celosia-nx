void expectDigest(const Pin &pin,const char *kind,const std::array<uint8_t,32> &digest,const char *expected)
{
    const auto actual=hexDigest(digest);
    if(actual!=expected) mismatch(std::string("Game publication: ")+pin.file+" "+kind+
        " SHA-256 actual="+actual+" expected="+expected);
}
