void expect(const Pin &pin,const char *name,uint32_t offset,uint32_t address,uint32_t actual,uint32_t expected)
{
    if(actual==expected) return;
    char message[256];
    std::snprintf(message,sizeof(message),
        "Game publication: %s %s offset=0x%x address=0x%08x actual=0x%08x expected=0x%08x",
        pin.file,name,offset,address,actual,expected);
    mismatch(message);
}
bool mainRange(uint32_t address,uint32_t bytes)
{
    for(const auto base:{0u,0x20000000u,0x80000000u,0xA0000000u}) {
        if(address<base) continue;
        const auto offset=address-base;
        if(offset<=DataMemory::MainBytes && bytes<=DataMemory::MainBytes-offset) return true;
    }
    return false;
}
uint32_t word(const DataMemory &memory,uint32_t address)
{
    std::array<uint8_t,4> value{};
    if(!memory.read(address,value.data(),value.size())) mismatch("Game publication: metadata exceeds data bounds");
    return uint32_t(value[0]) | (uint32_t(value[1])<<8) | (uint32_t(value[2])<<16) | (uint32_t(value[3])<<24);
}
void expectWord(const Pin &pin,const DataMemory &memory,const char *name,uint32_t base,uint32_t offset,uint32_t expected)
{expect(pin,name,offset,base+offset,word(memory,base+offset),expected);}
