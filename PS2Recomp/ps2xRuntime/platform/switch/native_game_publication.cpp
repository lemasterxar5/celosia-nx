void validateGamePublication(DataMemory &memory,const R5900Context &context,NativeFiles &files,Hasher hasher)
{
    if(!hasher) mismatch("Game publication: SHA-256 provider missing");
    const auto &pin=select(context);
    validateContext(pin,memory,context);validateLayout(pin,memory);
    const auto image=readImage(pin,files);
    expectDigest(pin,"native file",hasher(image),pin.rawDigest);
    const auto data=static_cast<const DataMemory &>(memory).mainRam();
    expectDigest(pin,"loaded static text",hasher(data.subspan(pin.text,pin.textBytes)),pin.textDigest);
}
